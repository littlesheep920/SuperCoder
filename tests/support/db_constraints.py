"""The MySQL CHECK constraints that the in-memory repositories must enforce too.

Why this exists
---------------
Four defects in the workflow paths passed every test and would have failed on the first real
insert: an empty correlation id, a runtime outside the allowed list, a rejected run with no
`finished_at`, and fixture hashes that were not hashes. Each one was a row the in-memory store
accepted and MySQL refuses. A test double that is more permissive than the store it replaces
lets exactly this class of bug reach production, so the rules are restated here once and every
fake calls them.

Each check is named after the constraint it mirrors in
`infra/migrations/0001_stage0_contract.sql`, so a failure points at the rule production would
have enforced. The list is not every constraint in the schema: identifiers generated by test
fixtures are not checked here, because they never come from application code. Everything the
application computes or copies from a request is.
"""

from __future__ import annotations

import re
from typing import Any, Mapping

HASH = re.compile(r"^sha256:[0-9a-f]{64}$")

RUN_RUNTIMES = frozenset(
    {"kiro", "claude-code", "cursor", "dify", "openai-compatible-agent-runtime"}
)
RUN_STATUSES = frozenset(
    {"queued", "running", "awaiting_approval", "succeeded", "failed", "cancelled", "timed_out"}
)
RUN_TERMINAL = frozenset({"succeeded", "failed", "cancelled", "timed_out"})

USAGE_ACTIONS = frozenset(
    {"discover", "resolve", "validate", "execute", "publish", "deprecation_warning"}
)
USAGE_STATUSES = frozenset({"started", "succeeded", "failed", "denied", "cancelled"})


class ConstraintViolation(AssertionError):
    """A row the database would refuse. Raised by a fake instead of storing it."""

    def __init__(self, constraint: str, detail: str) -> None:
        self.constraint = constraint
        super().__init__(f"{constraint}: {detail}")


def _is_hash(value: Any) -> bool:
    return isinstance(value, str) and HASH.match(value) is not None


def _non_empty(value: Any) -> bool:
    return isinstance(value, str) and len(value) > 0


def check_workflow_definition(row: Mapping[str, Any]) -> None:
    """`workflow_definition` CHECK constraints."""

    if not _is_hash(row.get("graph_hash")):
        raise ConstraintViolation(
            "ck_workflow_definition_hash", f"graph_hash {row.get('graph_hash')!r} is not sha256"
        )
    if not _non_empty(row.get("definition_schema_version")):
        raise ConstraintViolation(
            "ck_workflow_definition_schema", "definition_schema_version must not be empty"
        )
    if not isinstance(row.get("definition"), Mapping):
        raise ConstraintViolation("ck_workflow_definition_json", "definition must be an object")


def check_workflow_run(row: Mapping[str, Any]) -> None:
    """`workflow_run` CHECK constraints, applied to the row as it would be stored."""

    for field in ("definition_graph_hash", "resolution_snapshot_hash", "input_hash"):
        if not _is_hash(row.get(field)):
            raise ConstraintViolation(
                "ck_workflow_run_hashes", f"{field} {row.get(field)!r} is not sha256"
            )
    output_hash = row.get("output_hash")
    if output_hash is not None and not _is_hash(output_hash):
        raise ConstraintViolation("ck_workflow_run_hashes", f"output_hash {output_hash!r}")

    if not isinstance(row.get("resolution_snapshot"), Mapping):
        raise ConstraintViolation("ck_workflow_run_snapshot", "snapshot must be an object")

    if row.get("runtime") not in RUN_RUNTIMES:
        raise ConstraintViolation(
            "ck_workflow_run_runtime", f"runtime {row.get('runtime')!r} is not allowed"
        )

    status = row.get("status")
    if status not in RUN_STATUSES:
        raise ConstraintViolation("ck_workflow_run_status", f"status {status!r}")

    for field in ("requested_by", "idempotency_key", "correlation_id"):
        if not _non_empty(row.get(field)):
            raise ConstraintViolation("ck_workflow_run_required", f"{field} must not be empty")
    if not isinstance(row.get("timeout_seconds"), int) or row["timeout_seconds"] <= 0:
        raise ConstraintViolation("ck_workflow_run_required", "timeout_seconds must be > 0")

    if (row.get("output") is None) != (output_hash is None):
        raise ConstraintViolation(
            "ck_workflow_run_output_pair", "output and output_hash are set together or not at all"
        )
    if (row.get("approved_at") is None) != (row.get("approved_by") is None):
        raise ConstraintViolation(
            "ck_workflow_run_approval_pair", "approved_at and approved_by go together"
        )
    if status == "awaiting_approval" and not _non_empty(row.get("approval_gate")):
        raise ConstraintViolation(
            "ck_workflow_run_awaiting_gate", "awaiting_approval requires approval_gate"
        )
    if status in RUN_TERMINAL and row.get("finished_at") is None:
        raise ConstraintViolation(
            "ck_workflow_run_terminal_time", f"a {status} run requires finished_at"
        )
    if status == "succeeded" and output_hash is None:
        raise ConstraintViolation(
            "ck_workflow_run_success_output", "a succeeded run requires output_hash"
        )
    if status in {"failed", "timed_out"} and row.get("error_code") is None:
        raise ConstraintViolation(
            "ck_workflow_run_failure_code", f"a {status} run requires error_code"
        )
    started, finished = row.get("started_at"), row.get("finished_at")
    if started is not None and finished is not None and _utc(started) > _utc(finished):
        raise ConstraintViolation("ck_workflow_run_time_order", "started_at after finished_at")


def check_usage(row: Mapping[str, Any]) -> None:
    """`resource_usage` CHECK constraints."""

    if row.get("action") not in USAGE_ACTIONS:
        raise ConstraintViolation("ck_resource_usage_action", f"action {row.get('action')!r}")
    runtime = row.get("runtime")
    if runtime is not None and runtime not in RUN_RUNTIMES:
        raise ConstraintViolation("ck_resource_usage_runtime", f"runtime {runtime!r}")
    status = row.get("status")
    if status not in USAGE_STATUSES:
        raise ConstraintViolation("ck_resource_usage_status", f"status {status!r}")
    for field in ("input_hash", "output_hash"):
        value = row.get(field)
        if value is not None and not _is_hash(value):
            raise ConstraintViolation("ck_resource_usage_hashes", f"{field} {value!r}")
    for field in ("actor_id", "correlation_id"):
        if not _non_empty(row.get(field)):
            raise ConstraintViolation("ck_resource_usage_required", f"{field} must not be empty")
    if status != "started" and row.get("finished_at") is None:
        # The schema also requires duration_ms, which the SQL repository derives from the two
        # timestamps; finished_at is the part the caller must supply.
        raise ConstraintViolation(
            "ck_resource_usage_terminal", f"a {status} usage row requires finished_at"
        )
    if status in {"failed", "denied"} and row.get("error_code") is None:
        raise ConstraintViolation(
            "ck_resource_usage_failure", f"a {status} usage row requires error_code"
        )
    started, finished = row.get("started_at"), row.get("finished_at")
    if started is not None and finished is not None and _utc(started) > _utc(finished):
        raise ConstraintViolation("ck_resource_usage_time_order", "started_at after finished_at")


def _utc(moment):
    from datetime import timezone

    if moment.tzinfo is None:
        return moment.replace(tzinfo=timezone.utc)
    return moment.astimezone(timezone.utc)
